export type T = (text: string, vars?: Record<string, string | number>) => string;

function make(language: Language): T {
  return (text, vars) => {
    const entry = UI[text];
    let out = language === "en" || !entry ? text : entry[language === "kn" ? 0 : 1];
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        out = out.split(`{${name}}`).join(String(value));
      }
    }
    return out;
  };
}

const TRANSLATORS: Record<Language, T> = { en: make("en"), kn: make("kn"), hi: make("hi") };

export function translator(language: Language): T {
  return TRANSLATORS[language];
}
